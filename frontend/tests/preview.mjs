import { chromium } from "playwright";
import assert from "node:assert/strict";

const browser = await chromium.launch({ executablePath: process.env.CHROMIUM_PATH || "/usr/bin/chromium", headless: true, args: ["--no-sandbox"] });
const page = await browser.newPage({ viewport: { width: 1360, height: 900 } });
const errors = [];
let apiCalls = 0;
page.on("pageerror", error => errors.push(error.message));
await page.route("**/api/v2/**", route => { apiCalls++; return route.abort(); });
await page.route("**/api/auth/session/", route => route.fulfill({status: 200, contentType: "application/json", body: JSON.stringify({authenticated: false, username: null, csrf_token: "mock-csrf"})}));
try {
  await page.goto(process.env.TEST_URL || "http://127.0.0.1:5173");
  await page.getByRole("button", { name: "Preview connected pages" }).click();
  await page.getByText("UI preview · synthetic data").waitFor();
  assert.equal(await page.getByLabel("school", { exact: true }).inputValue(), "Example International University");
  const nav = page.getByRole("navigation", { name: "Study planning steps" });
  await nav.getByRole("button", { name: "Complete expenses" }).click();
  assert.match(await page.getByRole("main").innerText(), /Amount missing|Missing/);
  await nav.getByRole("button", { name: "Budget" }).click();
  assert.match(await page.getByRole("main").innerText(), /food needs an amount/i);
  assert.doesNotMatch(await page.getByRole("main").innerText(), /MISSING:food/);
  await page.getByText("View backend issue codes").first().click();
  assert.match(await page.getByRole("main").innerText(), /MISSING:food/);
  const calendar = page.getByRole("region", { name: "Payment calendar" });
  assert.match(await calendar.innerText(), /15 Nov 2026|Nov 15, 2026/);
  assert.match(await calendar.innerText(), /Not received · estimated/);
  assert.equal(await page.getByRole("button", { name: "Update 90-day calendar" }).isDisabled(), true);
  assert.equal(await page.getByRole("button", { name: "Update budget results" }).isDisabled(), true);
  await nav.getByRole("button", { name: "Funding" }).click();
  const comparison = page.getByRole("region", { name: "Compare funding and loan options" });
  assert.equal(await comparison.getByRole("article", { name: /Loan quote/ }).count(), 2);
  assert.match(await comparison.innerText(), /THB 19,500.00/);
  await comparison.getByText("Conditions to review").click();
  assert.match(await page.getByRole("main").innerText(), /Family support has not been received/);
  await comparison.getByRole("article", { name: "Loan quote preview-quote-two" }).getByRole("button", { name: "Review this quote" }).click();
  assert.equal(await page.getByLabel("Select quote").inputValue(), "preview-quote-two");
  assert.equal(await page.getByRole("button", {name: "Create application draft"}).isDisabled(), true);
  await page.setViewportSize({ width: 390, height: 844 });
  assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), true);
  await page.getByRole("button", { name: /Step 5 of 5/ }).click();
  assert.equal(await nav.isVisible(), true);
  await page.screenshot({ path: "/tmp/studyflow-preview-mobile.png", fullPage: true });
  await page.getByRole("button", { name: "Connect to Django instead" }).click();
  await page.getByRole("button", { name: "Preview connected pages" }).waitFor();
  assert.equal(apiCalls, 0);
  assert.deepEqual(errors, []);
  console.log("PASS: token-free connected preview, five screens, calendar, read-only boundary, mobile navigation, and zero Django requests.");
} finally { await browser.close(); }
