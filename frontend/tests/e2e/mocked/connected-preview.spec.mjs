import { test } from '@playwright/test';
import assert from "node:assert/strict";
import { screenshot } from "../../support.mjs";

test.use({ viewport: { width: 1360, height: 900 } });

test('token-free connected preview, five screens, calendar, read-only boundary, mobile navigation, and zero Django requests.', async ({ page }) => {
  const errors = [];
  let apiCalls = 0;
  page.on("pageerror", error => errors.push(error.message));
  await page.route("**/api/v2/**", route => { apiCalls++; return route.abort(); });
    await page.goto(process.env.TEST_URL || "http://127.0.0.1:5173");
    await page.getByRole("heading", { name: "A clearer plan for studying abroad." }).waitFor();
    assert.equal(await page.getByRole("navigation", { name: "Study planning steps" }).count(), 0);
    await page.getByRole("button", { name: "Explore the five steps" }).click();
    await page.getByRole("region", { name: "Read-only tour" }).waitFor();
    assert.match(await page.getByRole("region", { name: "Read-only tour" }).innerText(), /Nothing here is saved, confirmed, submitted, or sent to Django/);
    assert.match(await page.getByRole("region", { name: "Read-only tour" }).innerText(), /resolve conflicts/);
    assert.match(await page.getByLabel("Step 1 of 5: Confirm information").innerText(), /1 of 5/);
    assert.match(await page.locator(".student-progress").innerText(), /TOUR POSITION · NOTHING COMPLETED/);
    assert.match(await page.getByRole("region", { name: "Start with what your documents say." }).innerText(), /Example International University/);
    assert.match(await page.getByRole("region", { name: "Sources disagree" }).innerText(), /City campus or North campus/);
    assert.equal(await page.getByRole("button", { name: /Explore expenses in this demo/ }).evaluate(button => Boolean(button.compareDocumentPosition(document.querySelector('#preview-conflicts')) & Node.DOCUMENT_POSITION_PRECEDING)), true);
    assert.ok(await page.locator('.preview-story-panel').first().evaluate(panel => parseFloat(getComputedStyle(panel).paddingLeft) >= 20));
    await page.setViewportSize({ width: 390, height: 844 });
    assert.ok(await page.locator('.preview-story-panel').first().evaluate(panel => parseFloat(getComputedStyle(panel).paddingLeft) >= 20));
    assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), true);
    await page.setViewportSize({ width: 1360, height: 900 });
    await page.getByText("See original document evidence").click();
    await page.getByRole("button", { name: /Explore expenses in this demo/ }).click();
    const nav = page.getByRole("navigation", { name: "Study planning steps" });
    await nav.getByRole("button", { name: "Complete expenses" }).click();
    assert.match(await page.getByRole("main").innerText(), /amount unknown|missing/i);
    assert.match(await page.getByRole("region", { name: "Read-only tour" }).innerText(), /add or edit your own expenses/);
    assert.equal(await page.getByRole("button", { name: "Save expense revisions" }).count(), 0);
    assert.equal(await page.getByRole("button", { name: /Continue to Budget/ }).count(), 1);
    await page.getByRole("button", { name: /Continue to Budget/ }).click();
    await page.getByRole("heading", { name: "Your budget needs more information" }).waitFor();
    assert.match(await page.locator(".result-highlights").innerText(), /THB 42,000.00/);
    const walkthrough = page.getByRole("region", { name: "What could you do about the missing food cost?" });
    await page.setViewportSize({ width: 390, height: 844 });
    await walkthrough.getByRole("button", { name: "Find the missing food cost" }).click();
    const food = page.locator("#cost-preview-food");
    const bounds = await food.boundingBox();
    assert.ok(bounds && bounds.y >= 0 && bounds.y < 844, "Food cost should be in the phone viewport");
    assert.equal(await food.evaluate(element => element === document.activeElement), true);
    assert.equal(await food.getByRole("textbox").count(), 0);
    await food.getByRole("button", { name: /Try sample Food estimate/ }).click();
    await food.getByRole("button", { name: "Back to Budget" }).click();
    assert.match(await page.locator(".result-highlights").innerText(), /THB 54,000.00/);
    assert.match(await page.locator(".result-highlights").innerText(), /Complete mock result/);
    assert.match(await page.getByRole("note").innerText(), /campus conflict.*still unresolved/i);
    await page.getByText("Explore the detailed payment calendar").click();
    assert.match(await page.getByRole("region", { name: "Payment calendar" }).innerText(), /Food/);
    await page.getByRole("button", { name: /Step 3 of 5/ }).click();
    await nav.getByRole("button", { name: "Funding" }).click();
    assert.match(await page.locator(".funding-highlights").innerText(), /THB 34,000.00/);
    assert.match(await page.getByRole("region", { name: "Sample funding options" }).innerText(), /THB 19,500.00/);
    assert.match(await page.getByRole("region", { name: "Sample funding options" }).innerText(), /Not received/);
    await page.getByRole("button", { name: /Continue to Simulated application/ }).click();
    assert.match(await page.locator(".student-progress").innerText(), /TOUR POSITION · NOTHING COMPLETED/);
    await page.getByRole("button", { name: /Back to funding options/ }).click();
    await page.getByRole("button", { name: /Step 4 of 5/ }).click();
    await nav.getByRole("button", { name: "Complete expenses" }).click();
    await food.getByRole("button", { name: "Reset Food to missing" }).click();
    await food.getByRole("button", { name: "Back to Budget" }).click();
    assert.match(await page.locator(".result-highlights").innerText(), /THB 42,000.00/);
    await page.setViewportSize({ width: 1360, height: 900 });
    assert.equal(await page.locator(".backend-scenarios").isVisible(), false);
    await page.getByText("Compare low, base, and high scenarios").click();
    assert.equal(await page.locator(".backend-scenarios").isVisible(), true);
    assert.match(await page.getByRole("main").innerText(), /food needs an amount/i);
    assert.doesNotMatch(await page.getByRole("main").innerText(), /MISSING:food/);
    await page.getByText("Assumptions and result details").click();
    await page.getByText("View backend issue codes").first().click();
    assert.match(await page.getByRole("main").innerText(), /MISSING:food/);
    await page.getByText("Explore the detailed payment calendar").click();
    const calendar = page.getByRole("region", { name: "Payment calendar" });
    assert.match(await calendar.innerText(), /15 Nov 2026|Nov 15, 2026/);
    assert.match(await calendar.innerText(), /Not received · estimated/);
    assert.equal(await page.getByRole("button", { name: "Update 90-day calendar" }).count(), 0);
    assert.equal(await page.getByRole("button", { name: "Update budget results" }).count(), 0);
    await nav.getByRole("button", { name: "Funding" }).click();
    const comparison = page.getByRole("region", { name: "Compare funding and loan options" });
    assert.match(await comparison.locator(".funding-highlights").innerText(), /THB 22,000.00/);
    assert.match(await comparison.locator(".result-attention").innerText(), /Family support has not been received/);
    await comparison.getByText("Explore funding sources and plan details").click();
    await comparison.getByText(/Compare \d+ simulated loan quotes?/).click();
    assert.equal(await comparison.getByRole("article", { name: /Loan quote/ }).count(), 2);
    assert.match(await comparison.innerText(), /THB 19,500.00/);
    await comparison.getByText("Conditions to review").click();
    assert.match(await page.getByRole("main").innerText(), /Family support has not been received/);
    await comparison.getByRole("article", { name: "Loan quote preview-quote-two" }).getByRole("button", { name: "Review this quote" }).click();
    assert.match(await page.getByRole("region", { name: "A different quote is selected" }).innerText(), /does not change or submit an application/);
    assert.match(await page.getByRole("region", { name: "Review the terms" }).innerText(), /THB 39,000.00/);
    assert.match(await page.getByRole("main").innerText(), /simulated application is under review/i);
    await page.setViewportSize({ width: 390, height: 844 });
    assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), true);
    assert.equal(await page.locator(".student-more-menu").getByRole("button", { name: "Preview wallet & transfers" }).isVisible(), false);
    await page.getByRole("button", { name: /Step 5 of 5/ }).click();
    assert.equal(await nav.isVisible(), true);
    await page.screenshot({ path: screenshot('preview-mobile.png'), fullPage: true });
    await page.locator(".student-more-menu summary").click();
    await page.getByRole("button", { name: "Connect to Django instead" }).click();
    await page.getByRole("button", { name: "Explore the five steps" }).waitFor();
    assert.equal(await page.getByRole("link", { name: "Sign in to StudyFlow" }).isVisible(), true);
    assert.ok((await page.getByRole("link", { name: "Sign in to StudyFlow" }).boundingBox())?.y < 844);
    assert.equal(await page.getByRole("link", { name: "Sign in to StudyFlow" }).evaluate(element => element === document.activeElement), true);
    assert.equal(apiCalls, 0);
    assert.deepEqual(errors, []);
});
